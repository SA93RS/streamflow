import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

# Define vairables
L = 6
R1 = 170
R2 = 410
P = 100
w1 = 120
w2 = 120

# Create x and V array
x = np.linspace(0, L, 500)
V = np.zeros_like(x)

# Calculate shear
for i in range(len(x)):
  xi = x[i]

  if xi < 2:
    V[i] = R1 - w1 * xi
  elif xi < 4:
    V[i] = R1 - w1 * 2 - P
  else:
    V[i] = R1 - w1 * 2 - P + R2 - w2 * (xi -4)

# Graph data
plt.figure(figsize=(8, 4))
plt.plot(x, V, color='red', label='Shear (V)')
plt.xlabel('x')
plt.ylabel('V')
plt.title('Shear Diagram')
plt.grid(True)
plt.legend()
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

# Define variables
L = 6
R1 = 170
R2 = 410
P = 100
w1 = 120
w2 = 120

x = np.linspace(0, L, 500)
M = np.zeros_like(x)

# Evaluate with loop
for i in range(len(x)):
  xi = x[i]

  if xi < 2:
    M[i] = R1 * xi - (w1 * xi**2) / 2
  elif xi < 4:
    M[i] = R1 * xi - w1 * 2 * (xi - 10 - P * (xi -2))
  else:
    M[i] = (
        R1 * xi
        - w1 * 2 * (xi -1)
        - P * (xi - 2)
        + R2 * (xi - 4)
        - (w2 * (xi - 4)**2) / 2
    )

# Graph data
plt.figure(figsize=(8, 4))
plt.plot(x, M, color='blue', label='Moment (M)')
plt.xlabel('x')
plt.ylabel('M')
plt.title('Moment Diagram')
plt.grid(True)
plt.legend()
plt.show()

